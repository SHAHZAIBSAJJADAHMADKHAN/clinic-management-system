async def admin_appointments(doctor_id: UUID|None=None,date: date|None=None,status: str|None=None,_: Profile=Depends(require_admin),s: ClinicService=Depends(service)): return await s.admin_appointments(doctor_id,date,status)
@router.post('/admin/appointments/{appointment_id}/cancel')
async def admin_cancel(appointment_id: UUID,data: ReasonRequest,p: Profile=Depends(require_admin),s: ClinicService=Depends(service)): return await s.cancel(p,appointment_id,data.reason,admin=True)
@router.get('/admin/dashboard')
async def dashboard(_: Profile=Depends(require_admin),s: ClinicService=Depends(service)): return await s.dashboard()
